"""
Regenerate assets/js/data.js from data/species.csv and data/reactions.csv.
Run after editing either CSV:   python tools/build_data.py
(The website reads data.js, not the CSVs, so it also works when opened from disk.)
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NUMERIC = {"dHf_J_mol", "dGf_J_mol", "S0_J_molK", "A", "B_x1e3", "C_x1e6", "D_x1e-5",
           "Tmin_K", "Tmax_K", "Tb_K"}


def read(name):
    with open(ROOT / "data" / name, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        for k in list(r):
            if k in NUMERIC:
                r[k] = float(r[k]) if r[k].strip() else None
    return rows


data = {"species": read("species.csv"), "reactions": read("reactions.csv")}
js = ("/* Generated by tools/build_data.py from data/*.csv. Edit the CSVs, not this file. */\n"
      "(function (root) {\n  root.THERMO_DATA = " + json.dumps(data, ensure_ascii=False, indent=1)
      + ";\n  if (typeof module !== 'undefined') module.exports = root.THERMO_DATA;\n"
      "})(typeof window !== 'undefined' ? window : globalThis);\n")
(ROOT / "assets" / "js" / "data.js").write_text(js, encoding="utf-8")
print(f"wrote assets/js/data.js: {len(data['species'])} species, {len(data['reactions'])} reactions")
